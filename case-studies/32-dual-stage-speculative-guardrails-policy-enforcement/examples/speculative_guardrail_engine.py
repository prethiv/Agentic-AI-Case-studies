# 4. Stage 2: Deep Semantic Evaluator (Async LLM / OPA Engine)
# ============================================================================

class DeepSemanticEvaluator:
    """Asynchronous semantic policy engine (simulating LLM-as-a-judge or OPA)."""

    def __init__(
        self,
        simulated_latency_s: float = 0.25,
        restricted_tables: Optional[List[str]] = None,
        signing_key: str = "speculative-guardrail-secret-key-32",
    ):
        self.simulated_latency_s = simulated_latency_s
        self.restricted_tables = restricted_tables or ["restricted_payroll", "classified_personnel", "pci_vault"]
        self.signing_key = signing_key.encode("utf-8")

    async def evaluate(self, intent: ActionIntent) -> PolicyEvaluationResult:
        """Evaluates semantic policy invariants, data sovereignty, and RBAC rules."""
        t0 = time.perf_counter()

        # Non-blocking async simulation of semantic policy engine / OPA
        await asyncio.sleep(self.simulated_latency_s)

        violated: List[str] = []
        table = str(intent.arguments.get("table", "")).lower()
        query = str(intent.arguments.get("query", "")).lower()

        # 1. Restricted dataset access rule
        for rest in self.restricted_tables:
            if rest in table or rest in query:
                violated.append(f"RESTRICTED_DATASET_ACCESS_{rest.upper()}")

        # 2. Indirect prompt injection heuristic check
        prompt = str(intent.arguments.get("prompt", "")).lower()
        if "ignore previous instructions" in prompt or "system override" in prompt:
            violated.append("INDIRECT_PROMPT_INJECTION_RISK")

        # 3. Cross-region data sovereignty check
        region = str(intent.arguments.get("region", "US")).upper()
        if region not in ["US", "EU", "APAC"]:
            violated.append(f"SOVEREIGNTY_UNAUTHORIZED_REGION_{region}")

        latency_ms = (time.perf_counter() - t0) * 1000

        if violated:
            return PolicyEvaluationResult(
                evaluator_tier="STAGE_2_DEEP",
                verdict=PolicyVerdict.DENY,
                violated_policies=violated,
                latency_ms=latency_ms,
                details={"checked_tables": self.restricted_tables},
            )

        return PolicyEvaluationResult(
            evaluator_tier="STAGE_2_DEEP",
            verdict=PolicyVerdict.ALLOW,
            latency_ms=latency_ms,
            details={"checked_tables": self.restricted_tables},
        )

    def sign_clearance(self, intent_id: str, verdict: PolicyVerdict) -> str:
        """Generates an HMAC-SHA256 signature for the Two-Phase Commit clearance receipt."""
        msg = f"{intent_id}:{verdict.value}".encode("utf-8")
        return hmac.new(self.signing_key, msg, hashlib.sha256).hexdigest()

    def verify_clearance(self, intent_id: str, verdict: PolicyVerdict, signature: str) -> bool:
        """Verifies the clearance signature."""
        expected = self.sign_clearance(intent_id, verdict)
        return hmac.compare_digest(expected, signature)


