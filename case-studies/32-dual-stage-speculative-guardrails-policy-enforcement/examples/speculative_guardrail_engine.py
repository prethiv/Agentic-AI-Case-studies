# 5. Speculative Staging Buffer & Two-Phase Commit (2PC) Gate
# ============================================================================

@dataclass
class StagedObservation:
    """Encapsulates a speculatively executed tool result held in quarantine."""
    buffer_id: str
    intent_id: str
    result: Any
    staged_at: float
    sealed: bool = True
    committed: bool = False
    purged: bool = False


class SpeculativeStagingBuffer:
    """In-memory transactional quarantine buffer for uncommitted speculative actions."""

    def __init__(self):
        self._buffer: Dict[str, StagedObservation] = {}
        self._lock = asyncio.Lock()

    async def stage(self, intent_id: str, result: Any) -> StagedObservation:
        """Seals an observation in the staging buffer."""
        async with self._lock:
            buf_id = f"buf-{uuid.uuid4().hex[:8]}"
            obs = StagedObservation(
                buffer_id=buf_id,
                intent_id=intent_id,
                result=result,
                staged_at=time.perf_counter(),
            )
            self._buffer[intent_id] = obs
            return obs

    async def commit_and_release(self, intent_id: str) -> Tuple[bool, Any]:
        """Unbuffers and releases the staged result upon successful 2PC clearance."""
        async with self._lock:
            obs = self._buffer.get(intent_id)
            if not obs or obs.purged:
                return False, None
            obs.committed = True
            obs.sealed = False
            return True, obs.result

    async def discard_and_purge(self, intent_id: str) -> bool:
        """Instantly revokes and discards the staged observation on policy violation."""
        async with self._lock:
            obs = self._buffer.pop(intent_id, None)
            if obs:
                obs.purged = True
                obs.result = None
                return True
            return False


