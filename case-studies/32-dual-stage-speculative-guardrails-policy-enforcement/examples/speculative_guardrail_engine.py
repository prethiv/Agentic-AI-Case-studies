# 6. Speculative Policy Engine Orchestrator
# ============================================================================

class SpeculativePolicyEngine:
    """
    Main runtime orchestrator implementing the Dual-Stage Speculative Guardrail Pattern:
    1. Synchronous Stage 1 Fast-Path Filter (<15ms).
    2. Action Risk Classification Gate.
    3. Synchronous Deep Gate for High-Mutating Actions (Wait then execute).
    4. Speculative Parallel Execution for Low-Idempotent Actions (Stage in quarantine).
    5. Two-Phase Commit (2PC) Barrier with fail-closed timeout handling.
    """

    def __init__(
        self,
        deep_evaluator: Optional[DeepSemanticEvaluator] = None,
        fast_filter: Optional[FastPathFilter] = None,
        deep_timeout_s: float = 1.0,
    ):
        self.fast_filter = fast_filter or FastPathFilter()
        self.deep_evaluator = deep_evaluator or DeepSemanticEvaluator()
        self.staging_buffer = SpeculativeStagingBuffer()
        self.deep_timeout_s = deep_timeout_s
        self.execution_traces: List[ExecutionTrace] = []

    def evaluate_stage1_fast(self, intent: ActionIntent) -> PolicyEvaluationResult:
        """Direct invocation of deterministic Stage 1 filter."""
        return self.fast_filter.evaluate(intent)

    async def evaluate_stage2_deep(self, intent: ActionIntent) -> PolicyEvaluationResult:
        """Direct invocation of asynchronous Stage 2 deep evaluator."""
        return await self.deep_evaluator.evaluate(intent)

    async def execute_with_guardrails(
        self,
        intent: ActionIntent,
        tool_handler: Callable[[Dict[str, Any]], Coroutine[Any, Any, Any]],
    ) -> Tuple[bool, Any, ExecutionTrace]:
        """
        Orchestrates fast-path filtering, speculative tool execution, and the 2PC barrier.
        Returns: (success: bool, payload_or_rejection: Any, trace: ExecutionTrace)
        """
        t_start = time.perf_counter()

        # Step 1: Sub-15ms Deterministic Fast-Path Filter
        fast_result = self.evaluate_stage1_fast(intent)
        trace = ExecutionTrace(
            intent=intent,
            stage1_result=fast_result,
        )

        if fast_result.verdict == PolicyVerdict.DENY:
            trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
            trace.error_message = f"Action blocked by fast-path guardrail: {fast_result.violated_policies}"
            self.execution_traces.append(trace)
            return False, trace.error_message, trace

        # Step 2: Route by Action Risk Profile
        if intent.risk_profile == PolicyActionRisk.HIGH_MUTATING:
            # Synchronous Deep Gate: Block tool call until Deep Evaluator clears
            try:
                deep_result = await asyncio.wait_for(
                    self.evaluate_stage2_deep(intent),
                    timeout=self.deep_timeout_s,
                )
            except asyncio.TimeoutError:
                trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
                trace.error_message = "Deep policy evaluation timed out (fail-closed security invariant)"
                self.execution_traces.append(trace)
                return False, trace.error_message, trace

            trace.stage2_result = deep_result

            if deep_result.verdict == PolicyVerdict.DENY:
                trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
                trace.error_message = f"Action rejected by deep policy engine: {deep_result.violated_policies}"
                self.execution_traces.append(trace)
                return False, trace.error_message, trace

            # Deep policy PASS -> Dispatch tool handler
            tool_output = await tool_handler(intent.arguments)
            trace.committed = True
            trace.final_output = tool_output
            trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
            self.execution_traces.append(trace)
            return True, tool_output, trace

        else:
            # Low-Risk / Idempotent: Speculative Parallel Execution
            trace.speculative_executed = True

            async def wrapped_tool() -> Any:
                res = await tool_handler(intent.arguments)
                # Store in quarantine buffer
                await self.staging_buffer.stage(intent.intent_id, res)
                return res

            deep_task = asyncio.create_task(self.evaluate_stage2_deep(intent))
            tool_task = asyncio.create_task(wrapped_tool())

            # Await both parallel tasks with timeout protection on deep evaluator
            try:
                done, pending = await asyncio.wait(
                    [deep_task, tool_task],
                    timeout=self.deep_timeout_s,
                    return_when=asyncio.ALL_COMPLETED,
                )
            except Exception as ex:
                await self.staging_buffer.discard_and_purge(intent.intent_id)
                trace.error_message = f"Speculative pipeline exception: {str(ex)}"
                trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
                self.execution_traces.append(trace)
                return False, trace.error_message, trace

            if deep_task not in done:
                # Deep task timed out: purge speculative buffer (fail closed)
                deep_task.cancel()
                await self.staging_buffer.discard_and_purge(intent.intent_id)
                trace.error_message = "Deep policy evaluation timed out (speculative buffer discarded)"
                trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
                self.execution_traces.append(trace)
                return False, trace.error_message, trace

            deep_result = deep_task.result()
            trace.stage2_result = deep_result

            # Step 3: Two-Phase Commit (2PC) Barrier
            if deep_result.verdict == PolicyVerdict.DENY:
                # Discard and purge the quarantined observation immediately
                await self.staging_buffer.discard_and_purge(intent.intent_id)
                trace.committed = False
                trace.error_message = (
                    f"Speculative result revoked by deep policy check: {deep_result.violated_policies}"
                )
                trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
                self.execution_traces.append(trace)
                return False, trace.error_message, trace

            # Deep policy ALLOW: Unbuffer and release staged observation
            success, committed_output = await self.staging_buffer.commit_and_release(intent.intent_id)
            trace.committed = success
            trace.final_output = committed_output
            trace.total_latency_ms = (time.perf_counter() - t_start) * 1000
            self.execution_traces.append(trace)
            return True, committed_output, trace
