# 3. Action Risk Classifier Gate
# ============================================================================

class ActionRiskClassifierGate:
    """Inspects tool metadata and parameter schema to certify idempotent vs mutating risk."""

    IDEMPOTENT_PREFIXES = ("get_", "read_", "search_", "list_", "query_", "fetch_", "describe_")
    MUTATING_PREFIXES = ("delete_", "drop_", "write_", "update_", "insert_", "transfer_", "create_", "execute_")

    @classmethod
    def classify_intent(cls, tool_name: str, arguments: Dict[str, Any]) -> PolicyActionRisk:
        """Determines action risk tier based on tool semantics and parameter flags."""
        name_lower = tool_name.lower()

        # Parameter overrides (e.g., mutate=True, write=True) take precedence
        if arguments.get("mutate", False) is True or arguments.get("write", False) is True:
            return PolicyActionRisk.HIGH_MUTATING

        # Explicit tool name checks
        if any(name_lower.startswith(prefix) for prefix in cls.MUTATING_PREFIXES):
            return PolicyActionRisk.HIGH_MUTATING

        if any(name_lower.startswith(prefix) for prefix in cls.IDEMPOTENT_PREFIXES):
            return PolicyActionRisk.LOW_IDEMPOTENT

        # Safe default: if unknown, treat as HIGH_MUTATING to prevent state leakage
        return PolicyActionRisk.HIGH_MUTATING


