# 2. Stage 1: Deterministic Fast-Path Filter (<15ms)
# ============================================================================

class BloomFilter:
    """Lightweight in-memory Bloom filter for fast keyword membership screening."""

    def __init__(self, size: int = 10000, hash_count: int = 4):
        self.size = size
        self.hash_count = hash_count
        self.bit_array = [False] * size

    def _hashes(self, item: str) -> List[int]:
        hashes = []
        for seed in range(self.hash_count):
            h = int(hashlib.sha256(f"{seed}:{item}".encode("utf-8")).hexdigest(), 16)
            hashes.append(h % self.size)
        return hashes

    def add(self, item: str) -> None:
        for bit_index in self._hashes(item.lower()):
            self.bit_array[bit_index] = True

    def contains(self, item: str) -> bool:
        return all(self.bit_array[bit_index] for bit_index in self._hashes(item.lower()))


class FastPathFilter:
    """Sub-15ms deterministic guardrail: regexes, Bloom filters, entropy & decoding."""

    def __init__(self, blocked_keywords: Optional[List[str]] = None):
        self.fast_regexes = [
            # Standard US Social Security Numbers
            (re.compile(r"\b\d{3}-\d{2}-\d{4}\b"), "PII_SSN_DETECTED"),
            # Credit Card numbers (Visa, MasterCard, Amex, Discover)
            (re.compile(r"\b(?:\d{4}[- ]?){3}\d{4}\b"), "PII_CREDIT_CARD_DETECTED"),
            # Destructive shell / SQL expressions
            (re.compile(r"(?i)\b(rm\s+-rf\s+/|drop\s+database\b|truncate\s+table\b)"), "DESTRUCTIVE_COMMAND_DETECTED"),
            # AWS / Cloud Secret Key patterns
            (re.compile(r"\b(AKIA[0-9A-Z]{16})\b"), "CREDENTIAL_SECRET_DETECTED"),
        ]

        # Seed keyword Bloom filter
        self.bloom_filter = BloomFilter(size=5000, hash_count=3)
        self.exact_blacklist: Set[str] = set()
        default_blacklist = [
            "exfiltrate",
            "dump_credentials",
            "sudo_bypass",
            "shadow_admin",
            "disable_firewall",
        ]
        for kw in (blocked_keywords or default_blacklist):
            self.bloom_filter.add(kw)
            self.exact_blacklist.add(kw.lower())

    @staticmethod
    def _calculate_entropy(text: str) -> float:
        """Calculates Shannon entropy to detect high-entropy obfuscation or leaked keys."""
        if not text:
            return 0.0
        prob = [float(text.count(c)) / len(text) for c in dict.fromkeys(list(text))]
        return -sum(p * math.log2(p) for p in prob)

    @staticmethod
    def _normalize_and_decode(payload_str: str) -> List[str]:
        """Normalizes unicode and detects base64-encoded sub-strings for obfuscation inspection."""
        candidates = [payload_str]

        # Check for potential base64 chunks (multiples of 4, at least 16 chars)
        b64_matches = re.findall(r"[A-Za-z0-9+/]{16,}={0,2}", payload_str)
        for chunk in b64_matches:
            try:
                decoded = base64.b64decode(chunk, validate=True).decode("utf-8", errors="ignore")
                if len(decoded.strip()) > 4 and decoded.isprintable():
                    candidates.append(decoded)
            except (binascii.Error, UnicodeDecodeError):
                continue

        return candidates

    def evaluate(self, intent: ActionIntent) -> PolicyEvaluationResult:
        """Runs sub-15ms deterministic inspection across all arguments."""
        t0 = time.perf_counter()
        arg_string = str(intent.arguments)

        # 1. Normalization & Obfuscation Inspection
        normalized_strings = self._normalize_and_decode(arg_string)

        violated_policies: List[str] = []

        for target_str in normalized_strings:
            # Check deterministic regexes
            for pattern, policy_name in self.fast_regexes:
                if pattern.search(target_str):
                    violated_policies.append(policy_name)

            # Check Bloom filter + Exact Blacklist
            tokens = re.findall(r"\b[A-Za-z0-9_]+\b", target_str)
            for token in tokens:
                token_clean = token.lower()
                if self.bloom_filter.contains(token_clean):
                    if token_clean in self.exact_blacklist:
                        violated_policies.append(f"BLOCKLIST_KEYWORD_{token_clean.upper()}")

        latency_ms = (time.perf_counter() - t0) * 1000

        if violated_policies:
            return PolicyEvaluationResult(
                evaluator_tier="STAGE_1_FAST",
                verdict=PolicyVerdict.DENY,
                violated_policies=list(dict.fromkeys(violated_policies)),
                latency_ms=latency_ms,
                details={"inspected_candidates": len(normalized_strings)},
            )

        return PolicyEvaluationResult(
            evaluator_tier="STAGE_1_FAST",
            verdict=PolicyVerdict.ALLOW,
            latency_ms=latency_ms,
            details={"inspected_candidates": len(normalized_strings)},
        )


