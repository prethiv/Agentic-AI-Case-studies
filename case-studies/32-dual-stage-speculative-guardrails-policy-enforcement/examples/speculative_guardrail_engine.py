# 1. Domain Enums & Pydantic Data Contracts
# ============================================================================

class PolicyActionRisk(str, Enum):
    """Action risk tier governing execution routing."""
    LOW_IDEMPOTENT = "LOW_IDEMPOTENT"
    HIGH_MUTATING = "HIGH_MUTATING"


class PolicyVerdict(str, Enum):
    """Enforcement decision emitted by evaluators."""
    ALLOW = "ALLOW"
    DENY = "DENY"
    REDACT = "REDACT"


class ActionIntent(BaseModel):
    """Structured representation of an agent's intended tool invocation."""
    intent_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    tool_name: str
    arguments: Dict[str, Any]
    risk_profile: PolicyActionRisk
    agent_id: str
    session_id: str
    timestamp_utc: datetime.datetime = Field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc))


class PolicyEvaluationResult(BaseModel):
    """Telemetry and verdict artifact generated by an evaluation tier."""
    evaluator_tier: str  # "STAGE_1_FAST" or "STAGE_2_DEEP"
    verdict: PolicyVerdict
    violated_policies: List[str] = Field(default_factory=list)
    redacted_payload: Optional[Dict[str, Any]] = None
    latency_ms: float
    evaluated_at_utc: datetime.datetime = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc)
    )
    details: Dict[str, Any] = Field(default_factory=dict)


class TwoPhaseCommitReceipt(BaseModel):
    """Cryptographically signed audit receipt for 2PC barrier resolution."""
    receipt_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    intent_id: str
    verdict: PolicyVerdict
    committed: bool
    staging_buffer_id: str
    signature: str
    timestamp_utc: datetime.datetime = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc)
    )


class ExecutionTrace(BaseModel):
    """End-to-end execution audit ledger entry."""
    intent: ActionIntent
    stage1_result: PolicyEvaluationResult
    stage2_result: Optional[PolicyEvaluationResult] = None
    speculative_executed: bool = False
    committed: bool = False
    final_output: Any = None
    total_latency_ms: float = 0.0
    error_message: Optional[str] = None


